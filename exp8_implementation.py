# ============================================================
# ADVERTISING SPEND VS SALES IMPACT ANALYSIS
# LINEAR REGRESSION MODEL
# ============================================================


# ============================================================
# PART 1: IMPORT LIBRARIES
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score


# ============================================================
# PART 2: UPLOAD AND READ COMPLETE DATASET
# ============================================================

# Upload Excel file
uploaded = files.upload()

# Automatically detect the uploaded file name
file_name = list(uploaded.keys())[0]

# Read the Excel file
df = pd.read_excel(file_name)

# Display all rows and all columns
pd.set_option('display.max_rows', None)
pd.set_option('display.max_columns', None)
pd.set_option('display.width', None)
pd.set_option('display.max_colwidth', None)

print("File uploaded successfully:", file_name)
print("Dataset Shape:", df.shape)

print("\n========== COMPLETE DATASET ==========")
display(df)


# ============================================================
# PART 3: BASIC DATASET INFORMATION
# ============================================================

print("\n========== DATASET INFORMATION ==========")

print("Number of Rows:", df.shape[0])
print("Number of Columns:", df.shape[1])

print("\nColumn Names:")
print(df.columns.tolist())

print("\nData Types:")
print(df.dtypes)


# ============================================================
# PART 4: CHECK MISSING VALUES
# ============================================================

print("\n========== MISSING VALUE CHECK ==========")

print(df.isnull().sum())

# Fill missing numerical values with median
numeric_columns = df.select_dtypes(include=np.number).columns

for column in numeric_columns:
    if df[column].isnull().sum() > 0:
        df[column] = df[column].fillna(df[column].median())

print("\nMissing values after treatment:")
print(df.isnull().sum())


# ============================================================
# PART 5: REMOVE DUPLICATE ROWS
# ============================================================

print("\n========== DUPLICATE CHECK ==========")

duplicate_count = df.duplicated().sum()

print("Number of duplicate rows:", duplicate_count)

# Remove duplicate rows
df = df.drop_duplicates()

print("Dataset shape after removing duplicates:", df.shape)


# ============================================================
# PART 6: HANDLE STATISTICAL OUTLIERS
# USING IQR METHOD
# ============================================================

print("\n========== OUTLIER CHECK ==========")

# Select numerical columns
numeric_columns = df.select_dtypes(include=np.number).columns

for column in numeric_columns:

    Q1 = df[column].quantile(0.25)
    Q3 = df[column].quantile(0.75)

    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR
    upper_limit = Q3 + 1.5 * IQR

    outliers = ((df[column] < lower_limit) |
                (df[column] > upper_limit)).sum()

    print(column, "-> Outliers:", outliers)

    # Cap extreme values using IQR limits
    df[column] = df[column].clip(
        lower=lower_limit,
        upper=upper_limit
    )


# ============================================================
# PART 7: DISPLAY CLEANED DATASET
# ============================================================

print("\n========== CLEANED DATASET ==========")

print("Final Dataset Shape:", df.shape)

display(df)


# ============================================================
# PART 8: DEFINE INPUT FEATURES (X)
# AND TARGET VARIABLE (Y)
# ============================================================

# Advertising spending across different channels
X = df[
    [
        'YouTube_Ad_Spend_Lakh',
        'Instagram_Ad_Spend_Lakh',
        'Netflix_Ad_Spend_Lakh',
        'Prime_Video_Ad_Spend_Lakh',
        'JioHotstar_Ad_Spend_Lakh'
    ]
]

# Sales Revenue is the target variable
y = df['Sales_Revenue_Lakh']


print("\n========== FEATURES (X) ==========")
display(X)

print("\n========== TARGET (Y) ==========")
display(y)


# ============================================================
# PART 9: SPLIT DATA INTO TRAINING AND TESTING DATA
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("\n========== TRAIN TEST SPLIT ==========")

print("Training data:", X_train.shape[0], "rows")
print("Testing data:", X_test.shape[0], "rows")


# ============================================================
# PART 10: CREATE LINEAR REGRESSION MODEL
# ============================================================

model = LinearRegression()

# Train the Linear Regression model
model.fit(X_train, y_train)

print("\nLinear Regression model trained successfully!")


# ============================================================
# PART 11: MAKE SALES PREDICTIONS
# ============================================================

y_pred = model.predict(X_test)

print("\n========== PREDICTED SALES ==========")

for i in range(len(y_pred)):
    print(
        "Actual:",
        round(y_test.iloc[i], 2),
        " | Predicted:",
        round(y_pred[i], 2)
    )


# ============================================================
# PART 12: MODEL EVALUATION
# ============================================================

# Mean Absolute Error
MAE = mean_absolute_error(y_test, y_pred)

# Mean Squared Error
MSE = mean_squared_error(y_test, y_pred)

# Root Mean Squared Error
RMSE = np.sqrt(MSE)

# R-squared
R2 = r2_score(y_test, y_pred)


print("\n========== MODEL PERFORMANCE ==========")

print("Mean Absolute Error (MAE):", round(MAE, 4))
print("Mean Squared Error (MSE):", round(MSE, 4))
print("Root Mean Squared Error (RMSE):", round(RMSE, 4))
print("R-squared (R²):", round(R2, 4))


# ============================================================
# PART 13: ACTUAL VS PREDICTED SALES TABLE
# ============================================================

results = pd.DataFrame({
    'Actual Sales Revenue': y_test.values,
    'Predicted Sales Revenue': y_pred
})

print("\n========== ACTUAL VS PREDICTED SALES ==========")

display(results)


# ============================================================
# PART 14: REGRESSION COEFFICIENTS
# ============================================================

coefficients = pd.DataFrame({
    'Advertising Channel': X.columns,
    'Regression Coefficient': model.coef_
})

print("\n========== REGRESSION COEFFICIENTS ==========")

display(coefficients)

print("Intercept:", model.intercept_)


# ============================================================
# PART 15: LINEAR REGRESSION EQUATION
# ============================================================

print("\n========== LINEAR REGRESSION EQUATION ==========")

print(
    "Sales Revenue = "
    f"{model.intercept_:.4f}"
    f" + ({model.coef_[0]:.4f} × YouTube)"
    f" + ({model.coef_[1]:.4f} × Instagram)"
    f" + ({model.coef_[2]:.4f} × Netflix)"
    f" + ({model.coef_[3]:.4f} × Prime Video)"
    f" + ({model.coef_[4]:.4f} × JioHotstar)"
)


# ============================================================
# PART 16: ACTUAL VS PREDICTED SALES GRAPH
# ============================================================

plt.figure(figsize=(8, 6))

plt.scatter(y_test, y_pred)

# Perfect prediction reference line
plt.plot(
    [y_test.min(), y_test.max()],
    [y_test.min(), y_test.max()],
    linestyle='--'
)

plt.xlabel("Actual Sales Revenue (Lakh)")
plt.ylabel("Predicted Sales Revenue (Lakh)")
plt.title("Actual vs Predicted Sales Revenue")

plt.show()


# ============================================================
# PART 17: PREDICT SALES FOR NEW ADVERTISING SPENDING
# ============================================================

# Example new advertising spending
new_ad_spend = pd.DataFrame({

    'YouTube_Ad_Spend_Lakh': [20],

    'Instagram_Ad_Spend_Lakh': [15],

    'Netflix_Ad_Spend_Lakh': [10],

    'Prime_Video_Ad_Spend_Lakh': [12],

    'JioHotstar_Ad_Spend_Lakh': [8]

})


# Predict sales revenue
predicted_sales = model.predict(new_ad_spend)


print("\n========== NEW SALES PREDICTION ==========")

print("New Advertising Spending:")

display(new_ad_spend)

print(
    "Predicted Sales Revenue:",
    round(predicted_sales[0], 2),
    "Lakh"
)